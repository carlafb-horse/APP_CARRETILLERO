DROP SCHEMA IF EXISTS carretillero;
CREATE DATABASE IF NOT EXISTS carretillero;
USE carretillero;


CREATE TABLE operaciones (
    id INT PRIMARY KEY AUTO_INCREMENT,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    color VARCHAR(255) NOT NULL UNIQUE
);



CREATE TABLE plantas (
    id INT PRIMARY KEY AUTO_INCREMENT,
    codigo VARCHAR(255) NOT NULL UNIQUE,
    nombre VARCHAR(255) NOT NULL
);



CREATE TABLE metodos (
    id INT PRIMARY KEY AUTO_INCREMENT,
    nombre_operacion VARCHAR(255) NOT NULL,
    nombre_metodo VARCHAR(255) NOT NULL DEFAULT '',
    simbolo VARCHAR(255) DEFAULT '',
    tiempo INT NOT NULL,
    FOREIGN KEY (nombre_operacion) REFERENCES operaciones(nombre) ON DELETE CASCADE ON UPDATE CASCADE
);



CREATE TABLE turnos (
    id INT PRIMARY KEY AUTO_INCREMENT,
    turno VARCHAR(255) NOT NULL,
    jornada_inicio VARCHAR(255) NOT NULL,
    jornada_fin VARCHAR(255) NOT NULL,
    minutos_trabajo INT NOT NULL,
    id_planta INT NOT NULL,
    FOREIGN KEY (id_planta) REFERENCES plantas(id) ON DELETE CASCADE ON UPDATE CASCADE
);



CREATE TABLE puestos (
    id INT PRIMARY KEY AUTO_INCREMENT,
    numero INT DEFAULT '0',
    nombre VARCHAR(255) DEFAULT '',
    numero_operarios INT DEFAULT '0',
    id_turno INT NOT NULL,
    FOREIGN KEY (id_turno) REFERENCES turnos(id) ON DELETE CASCADE ON UPDATE CASCADE
);



CREATE TABLE embalajes (
    id INT PRIMARY KEY AUTO_INCREMENT,
    cliente VARCHAR(255) NOT NULL,
    proveedor VARCHAR(255) NOT NULL,
    referencia_componente VARCHAR(255) NOT NULL,
    hora TIME NOT NULL,
    cantidad INT NOT NULL DEFAULT '0',
    FOREIGN KEY (cliente) REFERENCES plantas(codigo) ON DELETE CASCADE ON UPDATE CASCADE
);



CREATE TABLE etapas (
    id INT PRIMARY KEY AUTO_INCREMENT,
    id_puesto INT NOT NULL DEFAULT '0',
    referencia_componente VARCHAR(255) NOT NULL DEFAULT '',
    cantidad_mover INT NOT NULL DEFAULT '0',
    operacion VARCHAR(255) NOT NULL DEFAULT '',
    distancia_total DOUBLE NOT NULL DEFAULT '0',
    PS14 DECIMAL(10, 2) DEFAULT '0',
    DS10 DECIMAL(10, 2) DEFAULT '0',
    CDL DECIMAL(10, 2) DEFAULT '0',
    CDC DECIMAL(10, 2) DEFAULT '0',
    M1 DECIMAL(10, 2) DEFAULT '0',
    PS15 DECIMAL(10, 2) DEFAULT '0',
    DI21 DECIMAL(10, 2) DEFAULT '0',
    DC113 DECIMAL(10, 2) DEFAULT '0',
    DS14 DECIMAL(10, 2) DEFAULT '0',
    DS15 DECIMAL(10, 2) DEFAULT '0',
    DC DECIMAL(10, 2) DEFAULT '0',
    D1 DECIMAL(10, 2) DEFAULT '0',
    W5 DECIMAL(10, 2) DEFAULT '0',
    W5_2 DECIMAL(10, 2) DEFAULT '0',
    TT DECIMAL(10, 2) DEFAULT '0',
    TT_2 DECIMAL(10, 2) DEFAULT '0',
    AL DECIMAL(10, 2) DEFAULT '0',
    G1 DECIMAL(10, 2) DEFAULT '0',
    P5 DECIMAL(10, 2) DEFAULT '0',
    numero_picadas INT NOT NULL DEFAULT '1',
    actividad_minutos DECIMAL(10, 2) DEFAULT '0',
    actividad_minutos_picadas DECIMAL(10, 2) DEFAULT '0',
    tiempo_distancia_total DECIMAL(10, 2) DEFAULT '0',
    orden INT NOT NULL DEFAULT '0',
    UNIQUE KEY id_puesto (id_puesto,referencia_componente,operacion),
    FOREIGN KEY (id_puesto) REFERENCES puestos(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (operacion) REFERENCES operaciones(nombre) ON DELETE CASCADE ON UPDATE CASCADE
);



